def corpus() -> list[str]:
    out: list[str] = []
    for item in BANK:
        for key in ("reference", "bad_line", "player_line", "opponent_line"):
            if key in item:
                out += [item[key]["ru"], item[key]["en"]]
        for option in item.get("options", []) or []:
            if "ru" in option:
                out += [option["ru"], option["en"]]
    out += EDGE
    # Порядок стабильный, дубликаты убраны: фикстура не должна дрожать от правок
    # порядка в банке.
    return sorted(set(out))


def render() -> str:
    rows = []
    for text in corpus():
        a = analyze(text)
        rows.append({
            "text": text,
            "moves": a.moves,
            "primary": a.primary,
            "arg": a.arg_quality,
            "words": a.words,
            "number": a.number,
            "mentions": [[m.value, m.kind, m.ranged, m.aside] for m in a.mentions],
            "day_number": a.day_number,
            "spin": a.spin,
        })
    return json.dumps({"source": "engine/techniques.py::analyze", "cases": rows},
                      ensure_ascii=False, indent=1) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    fresh = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
    if fresh == current:
        print("фикстура классификатора синхронна")
        return 0
    if args.check:
        print(f"РАСХОЖДЕНИЕ: {TARGET} устарел — запустите tools/gen_analyze_fixtures.py")
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(fresh, encoding="utf-8")
    print(f"обновлено: {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
