"""limits.py — скромные пределы на один адрес: партии, взгляды и темп ходов.

ПОЧЕМУ ЭТО ЕСТЬ. Сокет `/v1/realtime` — самый дорогой вход в продукт, и без
пределов его ёмкость упирается не в нас. ЗАМЕРЕНО (`tools/bench_load.py`,
офлайн, `NEGO_AI=off`, эта машина — два ядра, 4 ГБ): шлюз держит 2048
одновременных партий, которые ИГРАЮТ, — 6144 доигранных хода, ни одного отказа
и ни одной потери. Каждая такая партия имеет право звать модель зрения раз в
восемь секунд: это 256 платных вызовов в секунду с ОДНОГО адреса, а не
пятнадцать, как считала первая редакция этой шапки. Ход дороже взгляда втрое
(судья, реплика, синтез), и тем же прибором с одного адреса без придержки
проходило 1399 ходов в секунду. Единственной защитой был пароль, а пароль на
показе знают все, кому его назвали, — то есть защиты не было.

ЧТО ЛОМАЕТСЯ ПЕРВЫМ — НЕ ТО, ЧТО КАЖЕТСЯ. Ни память, ни дескрипторы: партия
стоит 0.10 МБ и один дескриптор при потолке в миллион. Первым насыщается
ЕДИНСТВЕННЫЙ цикл событий (0.9 ядра уже с пятисот партий), и дальше растёт не
число отказов, а очередь к нему: ход доходит до движка за 1 мс при одной партии,
за 122 мс при 128 и за 1423 мс при 2048 — 0.69 мс на каждую одновременную
партию. Продукт не падает, он замедляется; поэтому предел на адрес — это
решение ПРО КОШЕЛЁК, а не про ёмкость. Числа правятся только перезамером:
`python tools/bench_load.py --ramp 1,12,32,128,512,1024,2048`.

ПОЧЕМУ ПРЕДЕЛ НА АДРЕС, А НЕ НА ПОЛЬЗОВАТЕЛЯ. Пользователей у нас нет: партия
начинается с открытия сокета, и никакой личности за ним не стоит. Адрес — это
единственное, что известно про звонящего, и его достаточно, чтобы отличить
комнату людей от скрипта.

ПОЧЕМУ ЛОКАЛЬНЫЕ АДРЕСА НЕ ОГРАНИЧИВАЮТСЯ. Через 127.0.0.1 ходят OpenTalking
(:8210), приборы предпоказа и сам фронтенд в разработке — то же исключение и по
той же причине, что у пароля в `main.py`: замок стоит на входе с улицы, а не
между комнатами. Ограничить их значило бы уронить показ ровно тогда, когда к
нему готовятся.
"""

from __future__ import annotations

import os
import time
from typing import Optional

#: Локальные адреса — без пределов. Список тот же, что у пароля в `main.py`;
#: он импортирует его отсюда, чтобы однажды не открыть одну дверь и забыть
#: про вторую.
LOCAL_HOSTS = frozenset({"127.0.0.1", "::1", "localhost"})


#: СКОЛЬКО ПАРТИЙ ОДНОВРЕМЕННО С ОДНОГО АДРЕСА.
#:
#: Двенадцать — это оценка худшего случая показа: за одним NAT площадки сидит
#: стенд (три-четыре ноутбука), жюри смотрит со своих (ещё столько же) и кто-то
#: держит вторую вкладку. Восемь честных партий с одного адреса — обычный день;
#: двенадцать оставляет запас на перезагрузку вкладки, при которой возвращение
#: по `resume` на мгновение держит две партии сразу.
#:
#: НО «НАСТОЯЩИЙ ПОКАЗ ЭТОГО ПРЕДЕЛА НЕ УВИДИТ» — НЕПРАВДА, И ЭТО ЗАМЕРЕНО.
#: `tools/bench_load.py --mode room --room 20` с одного адреса: двенадцать
#: партий создано, восемь получили `too_many_sessions`. Комната жюри в двадцать
#: человек за одним NAT упирается сюда на тринадцатом столе — и упирается
#: первой, раньше памяти, дескрипторов и цикла событий. Что с этим делать на
#: площадке — в docs/hosting.md, раздел «Комната жюри»; коротко: поднимать надо
#: не одно число, а все три, потому что два из них выведены из этого.
#:
#: Ёмкости шлюза этот потолок не отражает: её замер — 2048 одновременных
#: партий, и упирается там уже не число сокетов, а задержка хода.
MAX_SESSIONS_PER_HOST = int(os.getenv("NEGO_MAX_SESSIONS_PER_HOST", "12") or 12)

#: СКОЛЬКО ВЗГЛЯДОВ МОДЕЛИ ЗРЕНИЯ В СЕКУНДУ С ОДНОГО АДРЕСА.
#:
#: Честный потолок считается, а не выбирается: слой камеры смотрит не чаще раза
#: в 8 секунд на партию (`perception/vision.py::_MIN_INTERVAL_S`), значит
#: двенадцать разрешённых партий дают 12/8 = 1.5 вызова в секунду. Два — это
#: полтора плюс запас на калибровку через `/api/vision/check`, которая идёт из
#: того же адреса и в ту же платную модель.
VISION_CALLS_PER_S = float(os.getenv("NEGO_VISION_CALLS_PER_S", "2") or 2)

#: ЗАПАС ВЁДРА. Комната начинает партии не по очереди, а одновременно: первый
#: кадр каждой партии — это «первый взгляд», он идёт сразу и не ждёт интервала.
#: Двенадцать таких плюс несколько калибровок — двадцать. Меньше означало бы
#: отказ ровно в ту секунду, когда показ начинается.
VISION_BURST = float(os.getenv("NEGO_VISION_BURST", "20") or 20)

#: СКОЛЬКО ХОДОВ В СЕКУНДУ С ОДНОГО АДРЕСА.
#:
#: Зрение считали внимательно, а ход — самый дорогой из всего: он зовёт судью,
#: потом поток реплики оппонента, потом синтез речи. Три платных вызова, и ни
#: одного предела на них не было. Довод про пароль здесь тот же, что и выше:
#: на показе его знают все, кому назвали.
#:
#: Потолок считается от живого замера, а не выбирается. Двенадцать разрешённых
#: партий; ход не может прийти чаще, чем сервер отвечает, а первый звук
#: оппонента приходит через 2.45 с (docs/latency.md). Значит машинный предел —
#: 12 / 2.45 ≈ 4.9 хода в секунду. Живой человек при этом думает и печатает
#: десяток секунд, то есть настоящая комната даёт около 1.2. Четыре — вдвое
#: выше человеческого потолка и ниже машинного: показ этого не увидит, скрипт
#: упрётся.
#:
#: ПРОВЕРЕНО НА ПРОВОДЕ, а не только выведено: `bench_load.py --mode pace` с
#: одного адреса даёт установившиеся ровно 4.0 хода в секунду, а без придержки
#: (офлайн) тот же адрес прогонял 1399. И переоткрытие сокета бюджета не
#: возвращает: свежая партия с ТОГО ЖЕ адреса ждала первого хода 248 мс (ровно
#: такт ведра), а с соседнего — 1 мс.
#:
#: И ЭТО ЧИСЛО ВЫВЕДЕНО ИЗ ПОТОЛКА ПАРТИЙ — связь, а не совпадение. Поднять
#: один потолок значит оставить комнату без темпа: `--mode room --room 30` при
#: `NEGO_MAX_SESSIONS_PER_HOST=40` и нетронутом ведре даёт ход до 3489 мс, а с
#: поднятыми вместе `NEGO_TURNS_PER_S=8` и `NEGO_TURN_BURST=48` — до 21 мс. Оба
#: раза все тридцать партий играют: это придержка, а не отказ, но на показе она
#: неотличима от задумавшегося сервера.
TURNS_PER_S = float(os.getenv("NEGO_TURNS_PER_S", "4") or 4)

#: ЗАПАС ВЁДРА. Комната садится за столы одновременно, и первый ход каждой
#: партии идёт сразу. Двенадцать таких плюс запас на возвращение по `resume`.
TURN_BURST = float(os.getenv("NEGO_TURN_BURST", "16") or 16)

#: Когда хостов в словарях становится больше этого, полные вёдра выбрасываются.
#: Ведро без записи неотличимо от полного, поэтому забывать их безопасно, а
#: расти вечно словарь не должен: адрес приходит с улицы.
_MAX_TRACKED_HOSTS = 4096


def exempt(host: str) -> bool:
    """Пустой адрес — тоже исключение: его подставляет TestClient-подобный
    транспорт без клиента, и молча ограничивать неизвестно кого нельзя."""
    return not host or host in LOCAL_HOSTS


# ---------------------------------------------------------------- партии

#: host → сколько партий этого адреса сейчас живы.
_live: dict[str, int] = {}


class Lease:
    """Одна занятая партия. Отпускается ровно один раз.

    Идемпотентность здесь не украшение: вытеснение отпускает аренду прежнего
    владельца НЕМЕДЛЕННО (его читатель может ещё висеть на `receive`), а потом
    её же попробует отпустить его `finally`. Второе списание увело бы счётчик
    в минус и выдало бы адресу лишнее место.
    """

    __slots__ = ("host", "_released")

    def __init__(self, host: str) -> None:
        self.host = host
        self._released = False

    def release(self) -> None:
        if self._released:
            return
        self._released = True
        left = _live.get(self.host, 1) - 1
        if left > 0:
            _live[self.host] = left
        else:
            _live.pop(self.host, None)


#: Аренда, которая ничего не занимала: локальный адрес. Отдельный объект, а не
#: None, чтобы вызывающему не приходилось помнить про два разных исхода успеха.
class _FreeLease(Lease):
    __slots__ = ()

    def release(self) -> None:
        return


def acquire_session(host: str) -> Optional[Lease]:
    """Занять место под партию. None — мест на этом адресе больше нет."""
    if exempt(host):
        return _FreeLease(host)
    if _live.get(host, 0) >= MAX_SESSIONS_PER_HOST:
        return None
    _live[host] = _live.get(host, 0) + 1
    return Lease(host)


def live_sessions(host: str) -> int:
    return _live.get(host, 0)


# ----------------------------------------------------------------- зрение

#: host → (сколько токенов осталось, когда считали). Ведро токенов, а не
#: счётчик в окне: окно пропускает двойной залп на стыке, а ведро — нет.
_vision: dict[str, tuple[float, float]] = {}


def _reap_vision(now: float) -> None:
    if len(_vision) <= _MAX_TRACKED_HOSTS:
        return
    for host, (tokens, last) in list(_vision.items()):
        if tokens + (now - last) * VISION_CALLS_PER_S >= VISION_BURST:
            _vision.pop(host, None)


def vision_allowed(host: str) -> bool:
    """Можно ли этому адресу ещё один взгляд платной модели.

    Списывает токен, если можно. Звать эту функцию нужно ТАМ, ГДЕ ВЫЗОВ И
    ПРОИСХОДИТ: слой камеры получает кадр несколько раз в секунду, а смотрит
    раз в восемь, и списание за каждый предложенный кадр опустошило бы ведро,
    ничего не потратив у провайдера.
    """
    if exempt(host):
        return True
    now = time.monotonic()
    _reap_vision(now)
    tokens, last = _vision.get(host, (VISION_BURST, now))
    tokens = min(VISION_BURST, tokens + (now - last) * VISION_CALLS_PER_S)
    if tokens < 1.0:
        _vision[host] = (tokens, now)
        return False
    _vision[host] = (tokens - 1.0, now)
    return True


# -------------------------------------------------------------------- ход

#: host → (токенов осталось, когда считали). То же ведро, что у зрения.
_turns: dict[str, tuple[float, float]] = {}


def _reap_turns(now: float) -> None:
    if len(_turns) <= _MAX_TRACKED_HOSTS:
        return
    for host, (tokens, last) in list(_turns.items()):
        if min(TURN_BURST, tokens + (now - last) * TURNS_PER_S) >= TURN_BURST:
            _turns.pop(host, None)


def turn_delay(host: str) -> float:
    """Сколько секунд этому адресу подождать перед ходом. Резервирует место.

    ПОЧЕМУ ЗАДЕРЖКА, А НЕ ОТКАЗ. Первая редакция отвечала «нельзя» и публиковала
    ошибку. Это ломало продукт: клиент, отправив ход, ждёт `response.done`, а
    ошибка внутри партии рисуется строкой в ленте и индикатор «оппонент
    печатает» не гасит. Отказанный ход оставлял человека перед вечным
    ожиданием — ровно тот молчащий сокет, о котором предупреждает соседний
    комментарий. Тот же дефект мгновенно повесил набор тестов.

    Задержка ломать нечего: живая комната её не почувствует (её темп вдвое ниже
    предела), а скрипт просто поедет медленнее — что и требовалось. Токены
    уходят в минус, поэтому очередь честная: пришедший раньше ждёт меньше.

    Звать НЕ на приёме куска ввода, а там, где ход действительно уходит в
    движок и в модели: `input.append` приходит десятками за одну реплику.
    """
    if exempt(host) or os.getenv("NEGO_AI", "").strip().lower() == "off":
        # Предел существует ради ПЛАТНЫХ вызовов: судьи, реплики, синтеза.
        # В офлайне их нет вовсе — придерживать нечего, а набор тестов
        # (`conftest.py` принудительно ставит `NEGO_AI=off`) иначе засыпает на
        # семнадцать лишних секунд, покупая этим ровно ничего.
        return 0.0
    now = time.monotonic()
    _reap_turns(now)
    tokens, last = _turns.get(host, (TURN_BURST, now))
    tokens = min(TURN_BURST, tokens + (now - last) * TURNS_PER_S) - 1.0
    _turns[host] = (tokens, now)
    return max(0.0, -tokens) / TURNS_PER_S


def paid_slot(host: str) -> bool:
    """Место под ОДИН платный вызов вне хода. False — бюджет адреса исчерпан.

    ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, ЕСЛИ ВЕДРО ТО ЖЕ. Ход придерживают, а не
    отказывают: клиент ждёт `response.done`, и отказ оставил бы человека перед
    вечным «оппонент печатает». У вызовов, которые НЕ ход, этой беды нет — у
    каждого есть честный бесплатный ответ:

    - подсказка тренера падает на детерминированную `views.compute_hint`;
    - тренер курса возвращает `note: null`, и карточка просто не рисуется;
    - «своя сделка» отвечает словами, что стол сейчас не собрать.

    Поэтому здесь отказ, а не сон: держать соединение занятым ради того, что
    и так умеет ответить бесплатно, незачем.

    ВЕДРО ОБЩЕЕ С ХОДОМ, И ЭТО НЕ ЛЕНЬ. Кошелёк один. Пределы на партии, на
    взгляды и на темп ходов закрывали три двери в платные модели, а четвёртая —
    подсказка, тренер курса и генерация сценария — стояла открытой: ни одна из
    них не ход, значит `turn_delay` их не касался вовсе. Кнопку 💡 можно жать
    сколько угодно раз подряд, и каждое нажатие — счёт от провайдера.
    """
    if exempt(host) or os.getenv("NEGO_AI", "").strip().lower() == "off":
        return True
    now = time.monotonic()
    _reap_turns(now)
    tokens, last = _turns.get(host, (TURN_BURST, now))
    tokens = min(TURN_BURST, tokens + (now - last) * TURNS_PER_S)
    if tokens < 1.0:
        _turns[host] = (tokens, now)
        return False
    _turns[host] = (tokens - 1.0, now)
    return True


# ------------------------------------------------------------- сообщения

def too_many_sessions(lang: str) -> str:
    """Отказ обязан называть причину и говорить, что делать. «Ошибка» без
    объяснения на показе неотличима от сломанного сервера."""
    if lang == "en":
        return ("Too many games running from this address. Close one of the open "
                "tabs, or wait for a slot to free up — games in progress are untouched.")
    return ("С этого адреса уже идёт слишком много партий. Закройте одну из "
            "открытых вкладок или подождите — идущие партии не тронуты.")


def too_many_generations(lang: str) -> str:
    """Отказ генерации «своей сделки». Она — самый дорогой вызов в продукте, и
    отказ обязан сказать, что делать дальше: готовые столы никуда не делись."""
    if lang == "en":
        return ("Too many custom deals are being built from this address right now. "
                "Try again in a few seconds, or pick one of the ready tables.")
    return ("С этого адреса сейчас слишком часто собирают свою сделку. "
            "Попробуйте через несколько секунд или выберите готовый стол.")


def vision_rate_limited(lang: str) -> str:
    if lang == "en":
        return ("The camera layer is looking too often from this address; it will "
                "pause for a moment. The game itself is unaffected.")
    return ("С этого адреса слой камеры смотрит слишком часто — он ненадолго "
            "берёт паузу. На саму партию это не влияет.")


# ------------------------------------------------------------------ тесты

def reset() -> None:
    """Забыть всё. Только для тестов: пределы процессные, а тесты — нет."""
    _live.clear()
    _vision.clear()
    _turns.clear()
