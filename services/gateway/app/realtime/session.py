"""session.py — состояние одной realtime-сессии.

Тонкая оболочка вокруг сессии движка. Всё, что относится к **игре** (шкалы,
цена, интересы, счёт), живёт в `engine.Session` и меняется только движком.
Здесь — только то, что относится к **разговору**: чей сейчас ход, какое
поколение ответа живо, какие слои включены, что оппонент успел сказать до того,
как его перебили.

Разделение неслучайно: движок обязан оставаться воспроизводимым и тестируемым
без единого упоминания сокетов, поколений и микрофона.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any, Optional

from app.ai.sanitize import sanitize
from app.realtime.bus import EventBus, new_generation_id


#: Предел накопленного хода игрока, знаков. Клиент обрезает на 2000 (см.
#: frontend/src/lib/net.ts::MAX_INPUT), но клиент — это то, что можно не
#: использовать: сокет открыт наружу, и `input.append` НАКАПЛИВАЕТ, поэтому без
#: предела здесь ход растёт до бесконечности и целиком уезжает в платные модели.
#: Комментарий в main.py про «зеркало предела хода по сокету» описывал этот
#: предел ещё до того, как он появился.
MAX_TURN_CHARS = 2000

#: Кадров в одном ходе. Смотрит модель всё равно только на последний
#: (vision.py берёт frames[-1]), поэтому копить пачку незачем — а вот память
#: она занимает настоящую: каждый кадр это base64 JPEG.
MAX_TURN_FRAMES = 8

#: Предел на ОДИН кадр, знаков base64. 320-пиксельный JPEG качества 0.6 весит
#: около 15 КБ; полмегабайта — это уже не наш кадр, а чей-то файл. Предел нужен
#: не ради памяти: кадр уезжает в платную модель зрения целиком, и без него
#: `input.append` с пятнадцатью мегабайтами — это оплаченный чужой файл.
#: Отсюда же его берёт `/api/vision/check`: двери две, число одно.
MAX_FRAME_B64 = 700_000

#: Предел на один кусок звука, байт PCM16. Чанк с микрофона — 20–40 мс, то есть
#: сотни байт; два мегабайта это минута речи разом. Больше — не наш клиент.
MAX_AUDIO_BYTES = 2_000_000

#: Длина ленты наблюдений, записей. Кадры гонит клиент, а сокет открыт наружу:
#: без предела лента растёт ровно столько, сколько кто-то готов слать кадров, и
#: целиком уезжает в разбор одним сообщением. Шестьдесят — это заведомо больше,
#: чем успевает набрать честная партия (взгляд не чаще раза в 8 секунд), поэтому
#: обрезание видно только тому, кто его и добивался.
MAX_VISION_NOTES = 60


@dataclass
class Layers:
    """Опциональные слои модальностей.

    ИНВАРИАНТ (docs/modalities.md): ни один слой не входит в `score_session`.
    Грейд со слоями обязан быть сравним с грейдом без них, иначе сертификат
    экзамена перестаёт что-то значить. Слои меняют только то, ЧТО ПОКАЗЫВАЕТ
    РАЗБОР и насколько живым выглядит оппонент.
    """
    probe: bool = False    # «читай лицо» — вопрос про реакцию оппонента
    voice: bool = False    # микрофон + голос оппонента
    camera: bool = False   # кадры в VLM для контекста присутствия
    avatar: bool = False   # лицо оппонента (состояния / липсинк)
    #: «Покерфейс» — упражнение, а не оценка. Считает кадры, на которых лицо
    #: несёт ЯВНОЕ выражение вместо нейтрального. Это наблюдаемый признак, а не
    #: вывод о внутреннем состоянии: «модель посмотрела и решила, что вы
    #: неуверенны» — псевдонаука, и в счёт такое не пускают (см. vision.py).
    #: Требует камеры: без кадров считать нечего.
    pokerface: bool = False

    @staticmethod
    def for_exam() -> "Layers":
        """Партия на зачёт фиксирует слои выключенными.

        ПОЧЕМУ ЭТО ЖИВЁТ НА СЕРВЕРЕ. Клиент их и так выключает, но правило,
        которое соблюдает только клиент, — не правило: `session.init` приходит
        из браузера, и `{"gameMode":"exam","layers":{"voice":true}}` сервер
        принимал как есть. Сертификат опирается на сопоставимость условий, а
        сопоставимость нельзя доверять тому, кого проверяешь.

        Зовётся на всех `protocol.REPRODUCIBLE_MODES` — экзамен и капстоун
        курса, — а не только на экзамене: у капстоуна условия сравнивают с
        эталонным прогоном движка, то есть с партией без единого слоя.
        """
        return Layers()

    @classmethod
    def from_dict(cls, d: dict[str, bool] | None) -> "Layers":
        d = d or {}
        camera = bool(d.get("camera"))
        return cls(probe=bool(d.get("probe")), voice=bool(d.get("voice")),
                   camera=camera, avatar=bool(d.get("avatar")),
                   # Покерфейс без камеры — включённый тумблер, за которым
                   # ничего не происходит. Гасим здесь, а не на клиенте:
                   # правило, которое соблюдает только клиент, не правило.
                   pokerface=bool(d.get("pokerface")) and camera)


@dataclass
class RealtimeSession:
    """Одна партия по одному сокету."""

    session_id: str
    engine_session: Any                 # engine.Session — истина игры
    lang: str = "ru"
    mode: str = "text"                  # text | voice
    #: Режим НА ПРОВОДЕ (`protocol.Mode`), а не режим экрана: `drill` — капстоун
    #: курса, который экран показывает обычным разбором. Отсюда сервер решает,
    #: идёт ли партия на зачёт, — `protocol.reproducible_run`.
    game_mode: str = "practice"         # practice | campaign | custom | exam | drill
    #: Репутация, принесённая из прошлых актов кампании. Нужна не только для
    #: сдвига доверия: с ней оппонент здоровается иначе — «наслышан о вас».
    reputation: Optional[float] = None
    layers: Layers = field(default_factory=Layers)
    #: id наложенного условия «стола дня», если партия сегодняшняя. Нужен
    #: клиенту, чтобы показать условие ЧЕСТНО: подпись «короткий стол» без
    #: применённого условия — ровно то, чего в продукте не бывает.
    daily: Optional[str] = None
    bus: EventBus = field(default_factory=EventBus)

    #: Адрес, с которого пришёл сокет. Нужен пределам на хост (`limits.py`):
    #: слой камеры считает бюджет взглядов по адресу, а знать его в момент
    #: взгляда неоткуда — сокет к тому времени уже за тремя слоями абстракции.
    client_host: str = ""

    #: Про исчерпанный бюджет зрения этому сокету уже сказали. Кадры идут
    #: потоком, и честность на каждом превратилась бы в поток ошибок, за
    #: которым не видно партии; молчать совсем тоже нельзя — молчащий слой
    #: неотличим от сломанной камеры. Поэтому ровно один раз за партию.
    vision_limit_told: bool = False

    #: Партию забрал другой сокет. ЗАЧЕМ ФЛАГ, А НЕ ПРОСТО ЗАКРЫТИЕ. Вытесненный
    #: сокет доживает свой `finally`, и без метки он сделал бы `store.release`
    #: (поставив живой партии срок в пять минут) или `store.drop` (вынув её
    #: из-под нового владельца). Метка говорит его `finally`: партия больше не
    #: твоя, уходи молча. Она же не даёт посчитать ход, присланный вдогонку.
    evicted: bool = False

    # --- владение поколением ------------------------------------------------
    #: Поколение — это одна попытка оппонента ответить. Ход игрока может
    #: породить их несколько: начал отвечать → перебили → отвечает заново.
    generation_id: Optional[str] = None

    # --- буфер входящего хода ----------------------------------------------
    #: `input.append` накапливает сюда, `input.commit` забирает. В голосовом
    #: режиме сюда падает расшифровка, в текстовом — то, что напечатали.
    pending_text: str = ""
    pending_frames: list[str] = field(default_factory=list)

    # --- что оппонент успел сказать вслух ----------------------------------
    #: Заполняется по мере стриминга. При перебивании этот кусок дописывается
    #: в историю (см. `interrupt()`), иначе оппонент не знает, на чём его
    #: оборвали, и повторяет сказанное — в голосе это слышно мгновенно.
    #: Приём взят из Open-LLM-VTuber `conversation_handler.py:112`
    #: (`heard_response` → `[Interrupted by user]`).
    spoken_so_far: str = ""

    #: Наблюдения камеры за сессию. Идут в контекст оппонента и в разбор,
    #: НО НИКОГДА в счёт. Хранятся здесь, а не в engine.Session, именно чтобы
    #: физически не оказаться на входе `score_session`.
    #:
    #: Плоские строки — это форма для ПРОМПТА: оркестратор берёт отсюда
    #: последние три и подаёт оппоненту (`ai/prompts.py::_observation_block`),
    #: где текст ещё и расплющивается, потому что пришёл из-за границы доверия.
    #: Номер хода там не нужен и мешал бы.
    observations: list[str] = field(default_factory=list)

    #: Та же правда для РАЗБОРА: что видела камера, на каком ходу и когда.
    #: Второе поле, а не другая форма первого, по одной причине — читателей
    #: два, и им нужно разное. Пишет оба `note_vision()`, поэтому разъехаться
    #: они не могут. В счёт не входит ни то, ни другое: `score_session`
    #: принимает `engine.Session`, а это `RealtimeSession`.
    vision_notes: list[dict] = field(default_factory=list)

    #: Начало партии по монотонным часам — от него считается время наблюдения.
    #: Монотонные, а не стенные: лента показывает «через сколько от начала», и
    #: перевод часов посреди партии не должен уводить её в прошлое.
    started_at: float = field(default_factory=time.monotonic)

    #: Сколько раз за партию лицо несло явное выражение вместо нейтрального.
    #: Живёт здесь по той же причине, что и наблюдения: в `engine.Session`
    #: этого поля нет, поэтому `score_session` до него не дотянется физически.
    tells: int = 0

    #: Сколько раз модель зрения ДОСМОТРЕЛА кадр до ответа — включая ответы
    #: «ничего примечательного», которые записью в ленту не становятся.
    #:
    #: ЗАЧЕМ ОТДЕЛЬНЫЙ СЧЁТЧИК, ЕСЛИ ЕСТЬ ЛЕНТА. Пустая лента отвечает сразу на
    #: два разных вопроса и не различает их: «слой смотрел и ему нечего было
    #: сказать» и «слой не посмотрел ни разу». Первое — штатная работа, второе —
    #: невставший слой, и человеку это разные новости. Без счётчика разбор молчит
    #: одинаково в обоих случаях, то есть работающий слой выглядит как мёртвый.
    #: В счёт не входит по той же причине, что и всё остальное здесь:
    #: `score_session` принимает `engine.Session`, а это `RealtimeSession`.
    vision_looks: int = 0

    # ------------------------------------------------------------------ ходы

    @property
    def turn_id(self) -> int:
        return self.engine_session.turn

    # -------------------------------------------------------------- зрение

    def note_vision(self, text: str = "", *, turn: Optional[int] = None,
                    expressive: Optional[bool] = None) -> None:
        """Записать один взгляд слоя камеры: что увидено и на каком ходу.

        ОДИН ВЗГЛЯД — ОДНА ЗАПИСЬ. Обстановку и выражение лица модель снимает с
        ОДНОГО кадра одним вызовом, поэтому в ленте они обязаны стоять одной
        строкой: «после хода 3 человек откинулся на спинку, и лицо себя выдало»
        — это одно событие, а не два.

        `turn` — сколько ходов было СДЕЛАНО к моменту кадра, а не номер
        будущего. Кадр приходит, пока человек сочиняет ответ или слушает
        оппонента, — то есть между ходами, и приписывать его следующему,
        которого ещё не было, значило бы датировать наблюдение будущим.

        `expressive is None` — модель про лицо не сказала (или слой выключен).
        Это НЕ «нет»: молчание модели и спокойное лицо — разные вещи, и
        считать их одинаково значило бы придумать данные.

        Кадр, на котором не увидено ничего и лицо спокойно, не записывается
        вовсе: пустая строка в ленте — это не наблюдение, а её отсутствие.
        """
        text = (text or "").strip()
        # Счётчик растёт РАНЬШЕ любого выхода: сюда приходит каждый досмотренный
        # кадр, и «модель ответила „ничего примечательного“» — это тоже работа
        # слоя, просто без записи в ленту.
        self.vision_looks += 1
        if text:
            self.observations.append(text)
        if not text and not expressive:
            return
        self.vision_notes.append({
            "turn": self.turn_id if turn is None else int(turn),
            "at_ms": max(0, round((time.monotonic() - self.started_at) * 1000)),
            "text": text,
            "expressive": expressive,
        })
        # Обрезаем хвостом: свежее наблюдение объясняет финал партии, а
        # тридцатое подряд «человек в кадре» не объясняет ничего.
        if len(self.vision_notes) > MAX_VISION_NOTES:
            del self.vision_notes[:-MAX_VISION_NOTES]

    def begin_generation(self) -> str:
        """Открыть новое поколение ответа оппонента."""
        self.generation_id = new_generation_id(self.session_id, self.turn_id)
        self.spoken_so_far = ""
        return self.generation_id

    def interrupt(self, reason: str = "barge_in") -> Optional[str]:
        """Погасить текущее поколение. Возвращает погашенный id (или None).

        Три вещи происходят здесь и только здесь:
          1. шина перестаёт выпускать хвост поколения наружу;
          2. услышанный кусок дописывается в историю разговора;
          3. поколение забывается, чтобы следующий ответ был новым.

        Гашение TTS, мозга и аватара — не тут: этим занимается оркестратор,
        потому что у него есть ссылки на живые задачи. Здесь — только то, что
        касается состояния разговора.
        """
        gen = self.generation_id
        if gen is None:
            return None
        self.bus.cancel(gen)
        # ЧЕРЕЗ САНИТАЙЗЕР, А НЕ СЫРЬЁМ. `spoken_so_far` копится из чанков
        # модели, то есть ДО санитайзера: тот судит реплику целиком и только
        # когда модель дописала, а при перебивании до конца дело не доходит
        # вовсе. Значит выход из роли («как языковая модель, я не могу вести
        # переговоры»), иероглифы и сырой markdown попадали в журнал как
        # собственные слова оппонента — и оттуда в стенограмму следующего хода
        # (`views._transcript` → промпт), где модель видела свой же выход из
        # роли как прецедент, и в разбор, где его читал человек.
        #
        # Отвергнутый кусок не пишется НИКАК: потерять метку «его перебили»
        # дешевле, чем показать человеку служебную строку и научить модель
        # повторять испорченную реплику.
        heard = sanitize(self.spoken_so_far)
        if heard:
            # Ровно та формулировка, что у Open-LLM-VTuber: оппонент видит в
            # истории собственную оборванную реплику и метку, что его прервали.
            # Многоточие не удваивается: `sanitize` ставит своё, когда обрезает
            # реплику по длине.
            text = heard if heard.endswith("…") else heard + " …"
            self.engine_session.log.append(
                {"role": "opp", "text": text, "interrupted": True}
            )
        self.generation_id = None
        self.spoken_so_far = ""
        return gen

    # ------------------------------------------------------------- накопление

    def append_input(self, *, text: str | None = None,
                     frames: list[str] | None = None) -> None:
        if text:
            # Пробел между кусками: ASR отдаёт фразы без хвостового пробела,
            # склейка встык слепила бы «ценаменя не устраивает».
            joined = (self.pending_text + " " + text).strip() if self.pending_text else text
            # Обрезаем НАКОПЛЕННОЕ, а не кусок: предел на кусок обходится
            # тысячей маленьких кусков, и именно так его и обошли бы.
            self.pending_text = joined[:MAX_TURN_CHARS]
        if frames:
            # Держим ХВОСТ: свежий кадр информативнее старого, а смотрит модель
            # всё равно только на последний.
            self.pending_frames = (self.pending_frames + list(frames))[-MAX_TURN_FRAMES:]

    def take_input(self) -> tuple[str, list[str]]:
        """Забрать накопленный ход и очистить буфер."""
        text, frames = self.pending_text.strip(), self.pending_frames
        self.pending_text, self.pending_frames = "", []
        return text, frames


# ---------------------------------------------------------------------------
# Что переживает обрыв связи
# ---------------------------------------------------------------------------
#
# ПОЧЕМУ ОТДЕЛЬНОЕ ХРАНИЛИЩЕ, А НЕ ПОЛЕ В `engine.Session`. Партию через обрыв
# проносит `app/session.py`: там лежит сессия ДВИЖКА, и положить ленту рядом с
# ней было бы на строку короче. Именно этого делать нельзя. Инвариант 6 держится
# не обещанием, а тем, что счёт физически не видит слоёв: `score_session`
# принимает `engine.Session`, а наблюдений в ней нет. Лента, переехавшая туда
# ради удобства, оказалась бы на входе счёта, и единственной защитой осталась бы
# дисциплина.
#
# ЗАЧЕМ ВООБЩЕ ЕЁ НЕСТИ. `_build_session` при возвращении строит НОВУЮ
# `RealtimeSession` вокруг старой сессии движка — то есть ходы, шкалы и цена
# возвращаются, а всё, что видела камера до обрыва, исчезало. Разбор после
# метро показывал ленту, начинающуюся с середины партии, и молчал о том, что
# начала он не знает. Лента с дырой хуже отсутствующей: дыры в ней не видно.

#: session_id → (положено_в, сколько_шла_партия, наблюдения, лента, взгляды).
_KEPT: dict[str, tuple[float, float, list[str], list[dict], int]] = {}

#: Столько же, сколько ждёт брошенную партию `app/session.py`: смысла держать
#: ленту дольше самой партии нет.
_KEEP_TTL_S = 300.0


def _reap_kept(now: float) -> None:
    for key in [k for k, v in _KEPT.items() if now - v[0] > _KEEP_TTL_S]:
        _KEPT.pop(key, None)


def keep_for_resume(session: "RealtimeSession") -> None:
    """Отложить наблюдения на случай, что к партии вернутся."""
    now = time.monotonic()
    _reap_kept(now)
    # Взгляды считаются наравне с записями: партия, где камера смотрела и
    # молчала, обязана пережить обрыв так же, как разговорчивая, — иначе после
    # метро разбор скажет «слой не поднялся» про слой, который работал.
    if not session.observations and not session.vision_notes and not session.vision_looks:
        return
    _KEPT[session.session_id] = (now, now - session.started_at,
                                 list(session.observations), list(session.vision_notes),
                                 session.vision_looks)


def restore_from_resume(session: "RealtimeSession", session_id: str) -> None:
    """Вернуть отложенное в продолженную партию.

    Часы партии продолжаются с того места, где оборвались, а не с нуля: иначе
    время в ленте пошло бы назад посреди списка. Пауза между обрывом и
    возвращением в них не входит — человека в эти секунды за столом не было.
    """
    kept = _KEPT.pop(session_id, None)
    if kept is None:
        return
    _at, elapsed, observations, notes, looks = kept
    session.observations[:0] = observations
    session.vision_notes[:0] = notes
    session.vision_looks += looks
    del session.vision_notes[:-MAX_VISION_NOTES]     # предел общий, а не на связь
    session.started_at = time.monotonic() - elapsed
