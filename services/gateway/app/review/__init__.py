"""«Глубокий разбор» — мультиагентный анализ сыгранной партии (решение владельца 19.10).

Обычный разбор не трогается: грейд, шкалы и советы считает движок, слово
наставника — модель поверх готового счёта. Глубокий разбор — ОТДЕЛЬНАЯ вещь по
кнопке в итогах: восемь агентов читают смысл реплик (уверенность, компетенции,
проговаривание мыслей, конкретика, понимание вопросов, реакция на уточнения,
последовательность, сверка с вводной), агент голоса слушает записанную речь,
агент мимики смотрит кадры. Сводка совмещает всё по времени, ищет совпадения
(«пауза + нахмуренные брови + „наверное“ на одном ходу») и для каждого вывода
называет уверенность — по числу примеров и по тому, сколько независимых
каналов его подтвердили.

ТРИ ГРАНИЦЫ — те же, что у слоёв (docs/modalities.md):

1. **Не входит в счёт.** Всё здесь живёт в `RealtimeSession` и в отчёте; ни
   одного поля в `engine.Session`. Числа компетенций — оценка МОДЕЛИ с
   плашкой «не влияет на грейд», а не второй грейд.
2. **Не заявлять того, чего нет.** Канал без данных называет причину («партия
   шла в чате», «камера была выключена»); цитата агента, которой нет в
   разговоре, выбрасывается; упавший агент назван, а не спрятан.
3. **Не на зачёт.** В экзамене и капстоуне (`REPRODUCIBLE_MODES`) записи нет и
   кнопки нет: там нет и судьи, а запись голоса и лица на зачёте — лишнее.

Модули:
  tape.py       запись партии: реплики со временем, речь, кадры (только в памяти)
  acoustics.py  голос без модели: паузы, темп, высота, громкость (numpy)
  agents.py     промпты и разбор ответов агентов
  merge.py      взвешивание: время, совпадения, уверенность — детерминированно
  runner.py     запуск агентов параллельно, с потолками и прогрессом
"""
