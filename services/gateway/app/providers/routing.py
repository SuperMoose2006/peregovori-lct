"""routing.py — какая модель отвечает за какую роль.

ПОЧЕМУ РОЛИ, А НЕ ОДНА МОДЕЛЬ. Раньше `NEGO_MODEL` задавал одну модель на всё.
В realtime это неверно по двум причинам сразу.

Первая — цена. Реплика оппонента звучит вслух, её слышит человек, и качество
русского там видно моментально. Судья каждого хода никто не читает целиком: он
выдаёт балл и одну строку коучинга. Платить за них одинаково — значит платить
за судью столько же, сколько за то, что реально слышно.

Вторая — задержка. Судья стоит **в критическом пути**: движок не может
посчитать ход, пока судья не вернул балл. Каждая лишняя секунда там — секунда
тишины в разговоре. Мозгу оппонента можно позволить думать дольше: он стримит,
и первая фраза уходит в TTS до того, как модель закончила.

Цены проверены живым запросом к `/api/v1/models` (см. docs/upstream-feature-matrix.md §4).
"""

from __future__ import annotations

import os
from typing import Literal

Role = Literal["opponent", "judge", "vision", "reasoning", "asr"]

#: Дефолты. Оппонент — не самая дорогая модель осознанно: рабочая лошадка
#: разработки, а `moonshotai/kimi-k3` включается переменной для демо и продакшена.
_DEFAULTS: dict[str, str] = {
    # Реплики оппонента. Сильный русский, низкая задержка, тот же семейный
    # эндпоинт, что у судьи и зрения → один прогретый пул соединений.
    "opponent": "google/gemini-3.5-flash-lite",
    # Судья каждого хода: в критическом пути, поэтому самое быстрое из приемлемых.
    "judge": "google/gemini-3.5-flash-lite",
    # Зрение: наблюдения о присутствии, не тонкий анализ. Дешёвое и быстрое.
    "vision": "google/gemini-3.1-flash-lite",
    # Тяжёлое рассуждение: финальный разбор и генерация сценария. Вне realtime —
    # они происходят один раз за партию, там можно себе позволить думать.
    "reasoning": "z-ai/glm-5.3",
    # ASR: единственная в каталоге дешёвая модель с аудио на входе.
    "asr": "google/gemini-3.7-flash",
}

_ENV = {
    "opponent": "NEGO_MODEL_OPPONENT",
    "judge": "NEGO_MODEL_JUDGE",
    "vision": "NEGO_MODEL_VISION",
    "reasoning": "NEGO_MODEL_REASONING",
    "asr": "NEGO_MODEL_ASR",
}

#: Значение, которое ставят в `NEGO_MODEL_OPPONENT`, когда нужно максимальное
#: качество. Держим константой, чтобы «переключатель в настройках» имел один
#: канонический адрес, а не пересказ строки по коду.
PREMIUM_OPPONENT = "moonshotai/kimi-k3"


def model_for(role: Role) -> str:
    """Модель для роли: переменная окружения > дефолт."""
    return os.getenv(_ENV[role], "").strip() or _DEFAULTS[role]


def describe() -> dict[str, str]:
    """Полная раскладка ролей — уходит в `/api/health` и в лог при старте.

    Смысл: на демо всегда должно быть видно, какой моделью сейчас говорит
    оппонент. Молчаливая подмена модели — самый неприятный способ узнать, что
    реплики стали хуже.
    """
    return {role: model_for(role) for role in _ENV}  # type: ignore[arg-type]
