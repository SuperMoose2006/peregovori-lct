"""numbers.py — числительные словами → цифры. Общая нормализация ввода.

ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. Движок распознаёт цену по цифрам (`MONEY_RE`). Пока ход
печатали на клавиатуре, это работало: люди пишут «300 000». Но говорят они
«триста тысяч» — и тот же по смыслу ход внезапно классифицировался как
`statement` вместо `offer`, с другим баллом аргументации и без тега «Оффер».

Замерено до правки:

    «Готов платить триста тысяч рублей.» → statement / 20 / []
    «Готов платить 300 000 рублей.»      → offer     / 26 / ['offer']

Это прямое нарушение требования паритета: **одна и та же реплика с клавиатуры и
голосом обязана давать один и тот же ход движка**. Распознавание речи иногда
нормализует числа само (замерено: gemini вернула «300 000» на «триста тысяч»),
но полагаться на настроение модели в вопросе о том, засчитана ли цена, нельзя.

ПОЧЕМУ В ДВИЖКЕ, А НЕ В ОРКЕСТРАТОРЕ. Если чинить на голосовом пути, то текст,
напечатанный словами, останется непонятым — а люди пишут «полтора миллиона» и
руками. И офлайн-ядро в браузере, которое зеркалит движок, разошлось бы с
сервером. Нормализация принадлежит `norm()`: единственной точке, через которую
проходит любой ход, откуда бы он ни пришёл.

Зеркало на клиенте: `frontend/src/mock/engine.ts`. Менять синхронно.

Область: количественные числительные до миллионов — то, чем торгуются. «Три
целых пять десятых» и порядковые («третий») сознательно не поддержаны: в
переговорах они не встречаются как цена, а ложное срабатывание хуже пропуска.
"""

from __future__ import annotations

import re

# Единицы, десятки, сотни. Формы приведены к тому виду, в котором их оставляет
# `norm()`: нижний регистр, «ё» → «е».
_RU_UNITS: dict[str, int] = {
    "ноль": 0, "один": 1, "одна": 1, "одну": 1, "два": 2, "две": 2, "три": 3,
    "четыре": 4, "пять": 5, "шесть": 6, "семь": 7, "восемь": 8, "девять": 9,
    "десять": 10, "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13,
    "четырнадцать": 14, "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17,
    "восемнадцать": 18, "девятнадцать": 19,
}
_RU_TENS: dict[str, int] = {
    "двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50,
    "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80, "девяносто": 90,
}
_RU_HUNDREDS: dict[str, int] = {
    "сто": 100, "двести": 200, "триста": 300, "четыреста": 400, "пятьсот": 500,
    "шестьсот": 600, "семьсот": 700, "восемьсот": 800, "девятьсот": 900,
}
#: Множители. Все падежные формы, которые реально произносят.
_RU_SCALES: dict[str, int] = {
    "тысяча": 1000, "тысячи": 1000, "тысяч": 1000, "тысячу": 1000,
    "миллион": 1_000_000, "миллиона": 1_000_000, "миллионов": 1_000_000,
}
#: «Полтора миллиона» — отдельным случаем: это не сумма слагаемых.
_RU_HALVES: dict[str, float] = {"полтора": 1.5, "полторы": 1.5}

_EN_UNITS: dict[str, int] = {
    "zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
    "seven": 7, "eight": 8, "nine": 9, "ten": 10, "eleven": 11, "twelve": 12,
    "thirteen": 13, "fourteen": 14, "fifteen": 15, "sixteen": 16,
    "seventeen": 17, "eighteen": 18, "nineteen": 19,
}
_EN_TENS: dict[str, int] = {
    "twenty": 20, "thirty": 30, "forty": 40, "fifty": 50, "sixty": 60,
    "seventy": 70, "eighty": 80, "ninety": 90,
}
_EN_SCALES: dict[str, int] = {"hundred": 100, "thousand": 1000, "million": 1_000_000}

_UNITS = {**_RU_UNITS, **_EN_UNITS}
_TENS = {**_RU_TENS, **_EN_TENS}
_HUNDREDS = dict(_RU_HUNDREDS)
_SCALES = {**_RU_SCALES, **_EN_SCALES}
_HALVES = dict(_RU_HALVES)

#: Слова-связки внутри числительного, которые не должны его разрывать.
_GLUE = {"и", "and"}

_ALL_NUMBER_WORDS = set(_UNITS) | set(_TENS) | set(_HUNDREDS) | set(_SCALES) | set(_HALVES)


def _fmt(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else str(value)


def _fold(tokens: list[str]) -> float | None:
    """Свернуть подряд идущие числительные в одно число.

    Классический алгоритм: копим «текущую» группу, множитель закрывает её и
    добавляет к итогу. `сто` работает и как сотня, и как множитель («сто
    тысяч»), поэтому обрабатывается в обеих ролях.
    """
    total = 0.0
    current = 0.0
    seen = False

    for token in tokens:
        if token in _GLUE:
            continue
        if token in _HALVES:
            current += _HALVES[token]
            seen = True
        elif token in _UNITS:
            current += _UNITS[token]
            seen = True
        elif token in _TENS:
            current += _TENS[token]
            seen = True
        elif token in _HUNDREDS:
            current += _HUNDREDS[token]
            seen = True
        elif token in _SCALES:
            scale = _SCALES[token]
            if scale == 100:
                # "two hundred" — сотня умножает набранное, а не закрывает группу.
                current = (current or 1) * 100
            else:
                total += (current or 1) * scale
                current = 0.0
            seen = True
        else:
            return None
    if not seen:
        return None
    return total + current


def spell_to_digits(text: str) -> str:
    """Заменить числительные словами на цифры. Остальное не трогать.

    Правило безопасности: одиночное числительное без множителя НЕ заменяется.
    «Три предложения» не должно превратиться в «3 предложения» и тем самым
    внезапно стать оффером — цена всегда произносится с единицей («триста
    тысяч», «полтора миллиона», «шестьдесят четыре тысячи»).
    """
    if not text:
        return text
    # Разделители групп внутри числа схлопываются: «300 000» → «300000».
    # Иначе одна и та же цена даёт РАЗНОЕ число слов, а от него зависит балл
    # аргументации — и паритет клавиатуры с голосом ломается на ровном месте
    # (замерено: 11 против 26 за одну и ту же реплику).
    text = _GROUP_SEP_RE.sub("", text)
    tokens = text.split(" ")
    # Пунктуация примыкает к слову: «шестьдесят четыре тысячи.» — последний
    # токен «тысячи.», и без отделения точки множитель не находился, а число
    # оставалось словами. Один раз это уже стоило нам паритета.
    bare = [_TRAIL_RE.sub("", t) for t in tokens]
    tails = [t[len(b):] for t, b in zip(tokens, bare)]

    out: list[str] = []
    i = 0
    while i < len(tokens):
        if bare[i] not in _ALL_NUMBER_WORDS:
            out.append(tokens[i])
            i += 1
            continue

        j = i
        group: list[str] = []
        while j < len(tokens) and (bare[j] in _ALL_NUMBER_WORDS
                                   or (bare[j] in _GLUE and group)):
            group.append(bare[j])
            j += 1
            # Пунктуация внутри группы обрывает числительное: «три, четыре»
            # это перечисление, а не тридцать четыре.
            if tails[j - 1]:
                break
        while group and group[-1] in _GLUE:
            group.pop()
            j -= 1

        has_scale = any(g in _SCALES and _SCALES[g] >= 1000 for g in group)
        value = _fold(group) if has_scale else None
        if value is None:
            out.extend(tokens[i:j])
        elif (out and _DIGITS_RE.fullmatch(out[-1])
              and group[0] in _SCALES and _SCALES[group[0]] >= 1000):
            # «70 тысяч» — множитель ПОСЛЕ цифр. Без этой ветки он приписывался
            # отдельным числом («70 1000»), и регулярка цены читала «70 100»:
            # человек называл семьдесят тысяч, а стол слышал семьдесят тысяч сто.
            # Замечено на живой партии — сделка закрылась на 29 902k за месяц.
            scale = _SCALES[group[0]]
            rest = _fold(group[1:]) or 0.0 if len(group) > 1 else 0.0
            prev = float(out[-1].replace(",", "."))
            out[-1] = _fmt(prev * scale + rest) + tails[j - 1]
        else:
            out.append(_fmt(value) + tails[j - 1])
        i = j
    return " ".join(out)


#: Экспортируется для теста паритета: он проверяет, что список слов не разошёлся
#: с зеркалом в `frontend/src/mock/engine.ts`.
NUMBER_WORDS = frozenset(_ALL_NUMBER_WORDS)

#: Чистое число без хвостов — им может оказаться предыдущий выведенный токен.
_DIGITS_RE = re.compile(r"\d+(?:[.,]\d+)?")

#: Примыкающая пунктуация, которую надо отделить от слова перед разбором.
_TRAIL_RE = re.compile(r"[.,!?%-]+$")

#: Пробел-разделитель групп разрядов внутри числа. Ровно три цифры справа,
#: иначе «по 86 88 за штуку» слиплось бы в «8688».
_GROUP_SEP_RE = re.compile(r"(?<=\d)[ \u00a0](?=\d{3}(?!\d))")
