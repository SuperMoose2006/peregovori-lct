"""judge.py — семантический судья на асинхронном пути.

Тот же судья, что и в `app/ai/judge.py`, но через асинхронного провайдера
OpenRouter. Промпт и — что важнее — **валидация** переиспользуются оттуда
целиком (`build_prompts`, `parse_judgement`): закрытый словарь приёмов,
зажим балла в 0..100 и проверка индекса интереса оплачены живым бейк-оффом
(docs/model-bakeoff.md). Переписывать их под новый транспорт означало бы
выбросить эту работу и заново собрать те же грабли.

ПОЧЕМУ СУДЬЯ КРИТИЧЕН ДЛЯ ЗАДЕРЖКИ. Он стоит в критическом пути: движок не
может посчитать ход, пока не получил балл, а оппонент не может отвечать, пока
движок не посчитал ход. Каждая секунда здесь — секунда тишины в разговоре.
Отсюда два решения: (1) отдельная быстрая модель через `role="judge"`,
(2) жёсткий бюджет времени — не дождались, идём по детерминированному
keyword-пути движка, как в офлайне.

ВТОРАЯ ПОПЫТКА. Синхронная версия при неудачном разборе JSON пробует ещё раз.
Здесь ретрай тоже есть, но только если остался бюджет: лучше отдать ход по
keyword-баллу, чем задержать ответ оппонента ещё на секунду.

СУДЬЯ НЕВОСПРОИЗВОДИМ, И ЭТО ИЗМЕРЕНО. Одна и та же реплика получает от одной и
той же модели разные баллы: разброс 5–15 очков, σ 2–5 (замер —
`tools/judge_spread.py`, числа в docs/judge-reproducibility.md). Три вывода
оттуда живут прямо в этом файле:

1. Температура не при чём. При `temperature=0` разброс ТОТ ЖЕ (σ 3.7 против
   4.1 — неразличимо на K=12). Недетерминизм провайдерский, не наш. Ноль стоит
   здесь потому, что судья не обязан быть креативным, а НЕ потому, что он от
   этого становится воспроизводимым: обещать второе значило бы заявить то,
   чего нет.
2. Усреднение не лечит. Медиана 5 параллельных вызовов оставляет σ 4.9 на
   пограничных репликах (модель бимодальна между двумя соседними значениями
   сетки) и стоит +570 мс из 719 мс критического пути (три голоса — +330 мс).
   Цена есть, эффекта нет.
3. Значит, лечить надо там, где цена ошибки максимальна, — на экзамене.
   `judge_enabled_for` выключает семантического судью в `gameMode="exam"`
   целиком: сертификат обязан быть воспроизводимым, а разброс балла хода на
   эталонной партии `good` переворачивал грейд B↔C при БАЙТ-В-БАЙТ одинаковом
   `overall` (74 во всех 36 прогонах) — через потолок техники `technique < 45`.
"""

from __future__ import annotations

import asyncio
import os
import time
from typing import Optional

from app.ai.judge import build_prompts, parse_judgement
from app.providers.openrouter import chat as orchat


def judge_enabled() -> bool:
    """Живой ли судья. По умолчанию — да, если есть облачный инференс.

    Отличие от синхронной версии: там дефолт зависел от того, какой бэкенд
    выбран (`cli`/`tmux` слишком медленные для пер-ходового вызова). Здесь
    бэкенд всегда сетевой и быстрый, поэтому семантика по умолчанию включена —
    это и есть рекомендованный профиль.
    """
    v = os.environ.get("NEGO_JUDGE", "").strip().lower()
    if v in ("1", "on", "true", "yes"):
        return True
    if v in ("0", "off", "false", "no"):
        return False
    return orchat.available()


#: Бюджет судьи. Подобран как компромисс: медленнее — и пауза между репликами
#: перестаёт быть похожей на человеческую заминку.
JUDGE_BUDGET_S = float(os.getenv("NEGO_JUDGE_BUDGET_S", "6.0"))

#: Температура судьи. Ноль — и не переменная окружения: «оценить реплику» это
#: не творческая задача, разнообразие здесь только вредит. Замер (см. шапку)
#: говорит, что воспроизводимости ноль НЕ даёт, поэтому число зафиксировано
#: тестом вместе с этим объяснением, а не оставлено на настройку.
JUDGE_TEMPERATURE = 0.0


def judge_enabled_for(game_mode: str | None) -> bool:
    """Судья на ЭТОМ столе. Экзамен — единственный режим, где ответ «нет»
    независимо от ключей, переменных и того, что прислал клиент.

    ПОЧЕМУ. Сертификат стоит ровно столько, сколько стоит его воспроизводимость.
    Экзамен уже фиксирует слои выключенными (`Layers.for_exam`) по третьему
    принципу — «грейд со слоями сравним с грейдом без них». Балл судьи в счёт
    входит, слои — нет, и именно поэтому он опаснее любого слоя: замер показал
    ту же партию с разными грейдами. Разброс не убирается ни температурой, ни
    усреднением (шапка файла), значит из экзамена уходит источник.

    Что экзамен теряет. Вето приёмов — защиту от спама ключевыми словами. Она
    не единственная: офлайновая лестница `frontend/test/fixtures/games.json`
    даёт спаму 27 из 100 (грейд F) против 77 (B) у нормальной партии, и это
    проверяется `test_reference_games.py`. Экзамен без судьи считается ровно
    тем движком, который эта лестница и описывает.
    """
    if (game_mode or "") == "exam":
        return False
    return judge_enabled()


async def judge_turn(context: str, player_text: str, lang: str = "ru",
                     interests: Optional[list] = None,
                     secondary: Optional[list] = None,
                     task: Optional[dict] = None) -> Optional[dict]:
    """Оценить реплику по смыслу. None → движок берёт keyword-балл."""
    if not (player_text or "").strip() or not judge_enabled():
        return None

    system, user = build_prompts(context, player_text, lang, interests, secondary, task)
    deadline = time.perf_counter() + JUDGE_BUDGET_S

    for attempt in (1, 2):
        remaining = deadline - time.perf_counter()
        if remaining <= 0.2:
            return None
        try:
            raw = await asyncio.wait_for(
                orchat.complete(system, user, role="judge", max_tokens=300,
                                temperature=JUDGE_TEMPERATURE, raw=True),
                timeout=remaining,
            )
        except (asyncio.TimeoutError, asyncio.CancelledError):
            return None
        except Exception:
            return None

        parsed = parse_judgement(raw or "", lang, interests, secondary)
        if parsed is not None:
            return parsed
        if attempt == 2:
            return None
    return None
