"""Ход — самый дорогой вход в продукт, и он был единственным без предела.

`limits.py` считал внимательно: сколько партий с одного адреса и сколько
взглядов модели зрения в секунду. Довод там записан прямо — «единственной
защитой был пароль, а пароль на показе знают все, кому его назвали».

Ровно тот же довод относится к ходу, а ход ДОРОЖЕ взгляда: он зовёт судью,
потом поток реплики оппонента, потом синтез речи. Три платных вызова против
одного, и ни одного предела.

Потолок посчитан, а не выбран: двенадцать разрешённых партий, первый звук
оппонента через 2.45 с (docs/latency.md) — машинный предел 12/2.45 ≈ 4.9 хода
в секунду. Живой человек думает и печатает десяток секунд, то есть настоящая
комната даёт около 1.2. Четыре — вдвое выше человеческого потолка и ниже
машинного.

ПРЕДЕЛ ЗАДЕРЖИВАЕТ, А НЕ ОТКАЗЫВАЕТ, и это исправление настоящей ошибки. Первая
редакция отвечала «нельзя» — а клиент, отправив ход, ждёт `response.done`;
ошибка внутри партии ложится строкой в ленту и индикатор «оппонент печатает» не
гасит. Отказанный ход оставлял человека перед вечным ожиданием. Тот же дефект
мгновенно повесил набор тестов НАВСЕГДА, и нашёл его сосед, а не я.
"""
from __future__ import annotations

import pytest

from app.realtime import limits


@pytest.fixture(autouse=True)
def _clean(monkeypatch):
    # `conftest.py` ставит `NEGO_AI=off` на весь набор, а предел в офлайне
    # намеренно не работает: платных вызовов нет, придерживать нечего. Здесь
    # проверяется само правило, поэтому ИИ на время теста «включаем».
    monkeypatch.setenv("NEGO_AI", "on")
    limits.reset()
    yield
    limits.reset()


def test_offline_is_never_delayed(monkeypatch):
    """Без ИИ предел молчит — и это не поблажка, а его определение.

    Он защищает счёт у провайдера. `NEGO_AI=off` означает, что провайдера нет:
    ни судьи, ни реплики, ни синтеза. Придерживать в этом режиме значило бы
    замедлять офлайн-игру и набор тестов, покупая ровно ничего.
    """
    monkeypatch.setenv("NEGO_AI", "off")
    host = "203.0.113.13"
    for _ in range(int(limits.TURN_BURST) * 5):
        assert limits.turn_delay(host) == 0.0


def test_a_room_of_people_waits_for_nothing():
    """Запас вёдра рассчитан на комнату, севшую за столы одновременно."""
    host = "203.0.113.7"
    waits = [limits.turn_delay(host) for _ in range(int(limits.TURN_BURST))]
    assert waits == [0.0] * int(limits.TURN_BURST), (
        f"честная комната начала ждать: {[w for w in waits if w]}")


def test_a_script_is_slowed_but_never_refused(monkeypatch):
    """Скрипт замедляется — и это единственное, ради чего предел есть.

    Задержка обязана расти, а не упираться в потолок: иначе после исчерпания
    вёдра темп снова стал бы неограниченным.

    Часы заморожены: между двумя вызовами подряд успевает натечь доля токена, и
    сравнение с точным шагом ловило бы реальное время, а не правило.
    """
    host = "203.0.113.8"
    monkeypatch.setattr(limits.time, "monotonic", lambda: 2000.0)
    for _ in range(int(limits.TURN_BURST)):
        limits.turn_delay(host)
    first = limits.turn_delay(host)
    second = limits.turn_delay(host)
    assert first > 0, "ведро не кончается — предела нет"
    assert second > first, f"задержка не растёт: {first} → {second}"
    assert second == pytest.approx(first + 1 / limits.TURNS_PER_S, rel=1e-6)


def test_the_bucket_refills_with_time(monkeypatch):
    """Ожидание временное: секунда возвращает ходы.

    Проверяем подменой часов, а не сном: тест, который спит, однажды начнёт
    моргать на загруженной машине — а сегодня несколько агентов гоняли набор
    одновременно, и прогон занял четверть часа.
    """
    host = "203.0.113.9"
    now = [1000.0]
    monkeypatch.setattr(limits.time, "monotonic", lambda: now[0])
    for _ in range(int(limits.TURN_BURST)):
        limits.turn_delay(host)
    assert limits.turn_delay(host) > 0
    now[0] += 10.0
    assert limits.turn_delay(host) == 0.0, "через десять секунд ход всё ещё ждёт"


def test_local_addresses_are_never_limited():
    """Замок стоит на входе с улицы, а не между комнатами.

    Через 127.0.0.1 ходят OpenTalking, приборы предпоказа и фронтенд в
    разработке. Ограничить их значило бы уронить показ ровно тогда, когда к
    нему готовятся, — та же оговорка, что у пароля и у зрения.
    """
    #: `testclient` в этот список НЕ входит намеренно. Соблазн был: без него
    #: интеграционные тесты выедают ведро. Но тем же исключением отключились бы
    #: и пределы на число партий и на зрение, которые эти же тесты проверяют
    #: нарочно, — три теста немедленно позеленели бы ни на чём. Задержка вместо
    #: отказа делает исключение ненужным: тест просто ждёт доли секунды.
    for host in ("127.0.0.1", "::1", "localhost", ""):
        for _ in range(int(limits.TURN_BURST) * 3):
            assert limits.turn_delay(host) == 0.0, f"локальный адрес {host!r} ограничили"


def test_hosts_do_not_share_a_bucket():
    """Сосед по площадке не должен исчерпать чужой предел."""
    a, b = "203.0.113.10", "203.0.113.11"
    for _ in range(int(limits.TURN_BURST)):
        limits.turn_delay(a)
    assert limits.turn_delay(a) > 0
    assert limits.turn_delay(b) == 0.0, "вёдра общие — один адрес запирает всех"


def test_no_move_is_ever_refused():
    """Главное свойство: отказа не существует ни при каком темпе.

    Клиент, отправивший ход, ждёт `response.done`. Отказ его не гасит — значит
    отказ равен вечному «оппонент печатает». Здесь это закреплено: сколько бы
    ходов ни пришло, ответ всегда «подожди столько-то», никогда «нет».
    """
    host = "203.0.113.12"
    for _ in range(int(limits.TURN_BURST) * 10):
        delay = limits.turn_delay(host)
        assert isinstance(delay, float) and delay >= 0.0, delay


def test_the_ceiling_is_above_a_real_room_and_below_a_script():
    """Само число обязано оставаться осмысленным, а не просто существовать.

    Двенадцать партий, первый звук через 2.45 с — машинный потолок 4.9 хода в
    секунду. Живая комната даёт около 1.2. Если однажды кто-то поставит предел
    ниже человеческого темпа, показ упрётся в него на глазах у жюри.
    """
    human_peak = limits.MAX_SESSIONS_PER_HOST / 10.0     # человек думает ~10 с
    machine_peak = limits.MAX_SESSIONS_PER_HOST / 2.45   # docs/latency.md
    assert human_peak < limits.TURNS_PER_S < machine_peak, (
        f"{limits.TURNS_PER_S} хода/с не между {human_peak:.1f} и {machine_peak:.1f}")
