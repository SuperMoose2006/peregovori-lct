"""Инвариант 4 для МАТЕРИАЛА: половина, которой просто нет.

`test_bilingual_content.py` рядом сторожит ЯЗЫК: английская строка написана
по-английски, русская — по-русски. Это ловит подмену текста и не ловит его
отсутствие: раздел фикстуры, помеченный `lang: "ru"`, не содержит ни одной
английской строки — значит и ни одной строки на чужом языке, и языковая
проверка проходит по нему с закрытыми глазами.

Разница не теоретическая. Лестница качества — семь партий, доказывающих, что
спам ниже базовой игры, — существовала только по-русски: 55 реплик, которых нет.
Из-за этого режим «Чтение стола» давал англоговорящему 9 партий вместо 12, а
анти-игровой порядок был ДОКАЗАН на русском и ОБЕЩАН на английском. Обходят же
защиту словами, и словари у языков разные.

Меряет это `tools/bilingual_audit.py` — прибор, который сперва воспроизводит
`games.scores.json` балл в балл по семи полям и только потом что-то утверждает
(не воспроизвёл — сломан ОН, код 2). Здесь он заперт в сборке: РАЗМЕР ДЫРЫ был
73, стал 0, и открыться обратно молча не должен.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1] / "tools" / "bilingual_audit.py"


def test_the_content_hole_stays_closed() -> None:
    result = subprocess.run([sys.executable, str(TOOLS)],
                            capture_output=True, text=True)
    assert result.returncode != 2, (
        "прибор сломан — калибровка не сошлась с games.scores.json, то есть он "
        "играет не ту игру, что продукт:\n" + result.stdout + result.stderr
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert "РАЗМЕР ДЫРЫ: 0" in result.stdout, result.stdout
