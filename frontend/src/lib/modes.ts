// modes.ts — какие партии идут НА ЗАЧЁТ.
//
// Зеркало `services/gateway/app/protocol.py::REPRODUCIBLE_MODES` (инвариант 8:
// офлайн-ядро обязано вести себя как сервер, и правило живёт в двух местах).
//
// Список отделён от кода, который им пользуется, по цене ошибки: пока вопрос
// «эта партия на зачёт?» решался тремя отдельными сравнениями с литерой "exam",
// капстоун курса проехал мимо всех трёх молча — и документ обещал
// воспроизводимость, которой не было.
import type { Mode } from "../types";

/** Итог обязан повторяться байт в байт: те же реплики — тот же результат.
 *  Отсюда уходит всё недетерминированное (семантический судья) и всё
 *  несравнимое (слои, условие «стола дня»). */
export const REPRODUCIBLE_MODES: readonly Mode[] = ["exam", "drill"];

export function reproducibleRun(mode: Mode | undefined | null): boolean {
  return !!mode && REPRODUCIBLE_MODES.includes(mode);
}
