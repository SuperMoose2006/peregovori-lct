// selfView.ts — видеть ли себя в созвоне: настройка игрока, а не слой.
//
// Плитка «Вы» в углу звонка — решение владельца (макет «как в Zoom», 19.10),
// а правило «человек, видящий себя, начинает следить за собой» (docs/
// modalities.md §2) — довод её прятать. Решили не выбирать за человека:
// переключатель в «Слоях» и кнопка на самой плитке меняют одну и ту же
// настройку, и она переживает перезагрузку. Камеры и оценки это не касается —
// ИИ видит кадры независимо от того, смотрит ли на них сам игрок.

export const SELF_VIEW_KEY = "dialog.selfview.v1";

/** Записи нет — выбора не было: плитка видна, как в макете владельца. */
export function parseSelfView(raw: string | null): boolean {
  return raw !== "0";
}
