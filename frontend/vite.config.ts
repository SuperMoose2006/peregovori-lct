import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

// Дев-сервер проксирует realtime-сессию и REST на гейтвей. Когда гейтвей не
// поднят, фронтенд уходит в офлайн-ядро (см. src/api/ws.ts) — `npm run dev`
// показывает продукт целиком в любом случае.
export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    proxy: {
      "/v1/realtime": {
        target: "ws://localhost:8010",
        ws: true,
        changeOrigin: true,
      },
      "/api": {
        target: "http://localhost:8010",
        changeOrigin: true,
      },
    },
  },
  build: {
    rollupOptions: {
      output: {
        // ЧТО ДЕЛИТ ЭТОТ БЛОК, А ЧТО — ДИНАМИЧЕСКИЙ ИМПОРТ.
        //
        // Куски сборки были и раньше, но все четыре импортировались статически:
        // браузер честно тянул их ВСЕ до первого экрана, и выигрыш сводился к
        // кешу между сборками. Разделение по ВРЕМЕНИ живёт теперь не здесь, а
        // в коде — `React.lazy` на экраны (App.tsx) и динамические импорты
        // транспортов (api/ws.ts). Rollup режет по этим границам сам.
        //
        // Здесь остались две ручные группы, и обе — про КЕШ, а не про время:
        //
        //   react  — не меняется от правки к правке и переживает наши сборки;
        //   course — сгенерированные девять блоков, 37 уроков и 69 упражнений.
        //            Данные меняются отдельным прогоном генератора, и держать
        //            их вне кода значит не переливать 127 КБ на каждой правке
        //            кнопки.
        //
        // ОФЛАЙН-ЯДРА ЗДЕСЬ БОЛЬШЕ НЕТ, И ЭТО НЕ ОПЕЧАТКА. Правило
        // `/src/mock/ → "engine"` затягивало в тот же файл всё, что движок
        // делит с домашним экраном: каталог сценариев, стол дня, форматирование,
        // нормализацию чисел. Кусок звался «офлайн-ядро», грузился первым
        // и был на две трети главной страницей. Без правила rollup оставляет
        // общее в главном файле, а движок уезжает туда, откуда его зовут.
        manualChunks(id: string) {
          if (id.includes("node_modules/react") || id.includes("node_modules/scheduler")) {
            return "react";
          }
          if (id.includes("/src/data/course.generated")) return "course";
          return undefined;
        },
      },
    },
  },
});
